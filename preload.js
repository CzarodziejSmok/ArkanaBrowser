const { contextBridge, ipcRenderer, webUtils } = require('electron');
contextBridge.exposeInMainWorld('api', {
  onOpenTab: cb => ipcRenderer.on('open-tab', (_e, u) => cb(u)),
  onShortcut: cb => ipcRenderer.on('shortcut', (_e, a) => cb(a)),
  setKeys: k => ipcRenderer.send('set-keys', k),
  pauseKeys: v => ipcRenderer.send('pause-keys', v),
  getInit: () => ipcRenderer.sendSync('get-init'),
  loadState: () => ipcRenderer.sendSync('load-state'),
  saveState: s => ipcRenderer.send('save-state', s),
  detach: p => ipcRenderer.send('detach', p),
  xdMove: p => ipcRenderer.invoke('xd-move', p),
  xdDrop: p => ipcRenderer.invoke('xd-drop', p),
  xdEnd: () => ipcRenderer.send('xd-end'),
  onXd: cb => ipcRenderer.on('xd', (_e, m) => cb(m)),
  setIcon: u => ipcRenderer.send('set-icon', u),
  setTitlebar: () => {},
  filePath: f => { try { return webUtils.getPathForFile(f); } catch { return ''; } },
  ffProbe: () => ipcRenderer.invoke('ff-probe'),
  ffRun: job => ipcRenderer.invoke('ff-run', job),
  onFfProgress: cb => ipcRenderer.on('ff-progress', (_e, m) => cb(m)),
  saveOut: m => ipcRenderer.invoke('save-out', m),
  htmlToPdf: html => ipcRenderer.invoke('html-to-pdf', html),
  changelog: () => ipcRenderer.invoke('changelog-get'),
  importDetect: () => ipcRenderer.invoke('import-detect'),
  importRun: (id, what) => ipcRenderer.invoke('import-run', id, what),
  importHtml: () => ipcRenderer.invoke('import-html'),
  importFolder: () => ipcRenderer.invoke('import-folder'),
  onPermAsk: cb => ipcRenderer.on('perm-ask', (_e, r) => cb(r)),
  permAnswer: (id, allow, remember) => ipcRenderer.send('perm-answer', id, allow, remember),
  permList: () => ipcRenderer.invoke('perm-list'),
  permDel: (o, k) => ipcRenderer.invoke('perm-del', o, k),
  permClear: () => ipcRenderer.invoke('perm-clear'),
  adblockSet: on => ipcRenderer.send('adblock-set', on),
  adblockStats: () => ipcRenderer.invoke('adblock-stats'),
  vaultState: o => ipcRenderer.invoke('vault-state', o),
  vaultFill: (id, o) => ipcRenderer.invoke('vault-fill', id, o),
  vaultSave: x => ipcRenderer.invoke('vault-save', x),
  vaultList: () => ipcRenderer.invoke('vault-list'),
  vaultReveal: id => ipcRenderer.invoke('vault-reveal', id),
  vaultDel: id => ipcRenderer.invoke('vault-del', id),
  vaultClear: () => ipcRenderer.invoke('vault-clear'),
  vaultNever: o => ipcRenderer.invoke('vault-never', o),
  httpGet: url => ipcRenderer.invoke('http-get', url),
  attention: () => ipcRenderer.send('attention'),
  winCtl: a => ipcRenderer.send('win-ctl', a),
  winState: () => ipcRenderer.invoke('win-state'),
  onWinState: cb => ipcRenderer.on('win-state', (_e, v) => cb(v)),
  exportConfig: (j, t) => ipcRenderer.invoke('export-config', j, t),
  importConfig: t => ipcRenderer.invoke('import-config', t),
  updInfo: () => ipcRenderer.invoke('upd-info'),
  updCheck: () => ipcRenderer.invoke('upd-check'),
  updDownload: () => ipcRenderer.invoke('upd-download'),
  updInstall: () => ipcRenderer.invoke('upd-install'),
  updOpen: () => ipcRenderer.invoke('upd-open'),
  updSet: c => ipcRenderer.send('upd-set', c),
  onUpd: cb => ipcRenderer.on('upd-event', (_e, s) => cb(s))
});
